def orc_cmd(cli, name):
    orc = shlex.quote(str(ORC))
    return orc if cli == "claude" else f"{orc} --as {name}"


def values_for(cli, name):
    caps = CLIS[cli]["caps"]
    orc = orc_cmd(cli, name)
    skills = sorted(p.name for p in (ROOT / "shared/skills").iterdir() if (p / "SKILL.md").exists())
    values = {
        "AGENT_NAME": name, "AGENT": name, "MULTIPLEXER": ORCHESTRATORS[name]["multiplexer"],
        "DOCS_ROOT": str(ROOT / "shared/docs"), "ROLES_ROOT": str(ROOT / "shared/roles"),
        "SKILLS_ROOT": str(ROOT / "shared/skills"), "SKILLS_LIST": ", ".join(f"`{s}`" for s in skills),
        "ORC": orc, "REPORTS": str(state_dir() / "reports"),
        "LAUNCH": CLIS[cli]["launch"].format(name=name),
        "PANES_ENTRY": (f"`/{name}-panes [core|judges|review|all|<role>...]` runs `{orc} panes`"
                        if "commands" in caps else
                        f"When the user asks for role panes, run `{orc} panes [core|judges|review|all|<role>...]`"),
    }
    vendor = ORCHESTRATORS[name].get("vendor_skill")
    if vendor:
        up = json.loads(read(f"{vendor}/UPSTREAM.json"))
        values["HERDR_SKILL_REF"] = f"{up['ref']}, sha256 {up['sha256'][:12]}"
    return values


def glossary(cli):
    v, label = VOCAB[cli], CLIS[cli]["label"]
    hooks = ("A guard hook and a phase hook run for you; the layer describes them."
             if "hooks" in CLIS[cli]["caps"] else
             "None run for you here. Where a rule would need one, the layer says what to do instead.")
    return (f"# Tool vocabulary ({label})\n\n"
            f"This prompt, its commands and the docs it points to are written for any CLI. They say "
            f"\"ask tool\", \"subagent tool\", \"shell tool\" and \"todo tool\"; a few ported docs name "
            f"Claude Code tools instead. In {label}, read both as follows:\n\n"
            f"- Ask tool (`AskUserQuestion`): {v['ask']}.\n"
            f"- Subagent tool (the Agent tool with `subagent_type: <role>`; \"the internal Claude Code "
            f"subagent\" means the internal subagent of that name): {v['subagent']}.\n"
            f"- Background subagents (the Agent tool's `run_in_background`): {v['background']}.\n"
            f"- Shell tool (the Bash tool, its `timeout` and `run_in_background`): {v['shell']}.\n"
            f"- Todo tool (TodoWrite): {v['todo']}.\n"
            f"- Skills (the Skill tool): {v['skills']}.\n"
            f"- MCP tools (`mcp__<server>__<tool>`): the same tool when that server is configured here "
            f"(its name may differ); otherwise take the text's path for when it is unavailable.\n"
            f"- Hooks: {hooks}\n\n")


def orchestrator_prompt(cli, name):
    caps, values = CLIS[cli]["caps"], values_for(cli, name)

    def part(rel):
        return fill(strip_comments(conditionals(read(rel), caps)), values)

    body = glossary(cli) + part("shared/core/odd-core.md") + "\n" + part("layers/common.md") + "\n" \
        + part(f"layers/{name}.md")
    vendor = ORCHESTRATORS[name].get("vendor_skill")
    if vendor:
        up = json.loads(read(f"{vendor}/UPSTREAM.json"))
        skill = re.sub(r"\A---\n.*?\n---\n", "", read(f"{vendor}/SKILL.md"), flags=re.S)
        body += (f"\n---\n\nThe `herdr` skill follows, verbatim except for its frontmatter "
                 f"({up['ref']}, {up['source']}).\n\n" + skill.lstrip())
    return body


def description(cli, name):
    meta = ORCHESTRATORS[name]
    return f"{meta['summary']} Use as the primary agent: {CLIS[cli]['launch'].format(name=name)} inside {meta['pane']}."


def role_body(role):
    return strip_comments(read(f"shared/roles/{role['name']}.md")) + SUBAGENT_NOTE


def command_parts(cli, name, cmd):
    fm, body = split_frontmatter(fill(read(f"layers/commands/{cmd}.md"), values_for(cli, name)))
    desc = re.search(r"^description:\s*(.*)$", fm, flags=re.M)
    return fm, (desc.group(1).strip() if desc else ""), body


# ----------------------------------------------------------- per-CLI plans
def base_dir(cli, scope, project):
    if scope == "project":
        sub = {"claude": ".claude", "opencode": ".opencode", "agy": ".agents", "codex": ".codex",
               "cursor": ".cursor"}[cli]
        return project / sub
    return {"claude": home() / ".claude",
            "opencode": Path(os.environ.get("XDG_CONFIG_HOME") or home() / ".config") / "opencode",
            "agy": home() / ".gemini/config", "codex": codex_home(), "cursor": home() / ".cursor"}[cli]


def plan(cli, scope, project, agents):
    """Files to write as {path: text}, plus the paths that would duplicate a name (agy)."""
    base = base_dir(cli, scope, project)
    files, shadows = {}, []
    if cli == "claude":
        for name in agents:
            files[base / f"agents/{name}.md"] = frontmatter(
                [("name", name), ("description", description(cli, name)),
                 ("color", ORCHESTRATORS[name]["color"])]) + orchestrator_prompt(cli, name)
            for cmd in COMMANDS:
                fm, _, body = command_parts(cli, name, cmd)
                files[base / f"commands/{name}-{cmd}.md"] = (
                    f"---\n# {MARK} from {ROOT}. Edit the sources there and re-run it.\n{fm}\n---\n{body}")
        for r in roles():
            files[base / f"agents/{r['name']}.md"] = frontmatter(
                [("name", r["name"]), ("description", r["description"]),
                 ("tools", ", ".join(r["tools"])), ("model", r.get("model"))]) + role_body(r)
    elif cli == "opencode":
        for name in agents:
            files[base / f"agents/{name}.md"] = frontmatter(
                [("description", description(cli, name)), ("mode", "primary"),
                 ("color", ORCHESTRATORS[name]["hex"])]) + orchestrator_prompt(cli, name)
            for cmd in COMMANDS:
                _, desc, body = command_parts(cli, name, cmd)
                files[base / f"commands/{name}-{cmd}.md"] = frontmatter(
                    [("description", desc), ("agent", name)]) + body.lstrip()
        for r in roles():
            perms = [{"action": "edit", "resource": "*", "effect": "deny"}] if read_only(r) else None
            files[base / f"agents/{r['name']}.md"] = frontmatter(
                [("description", r["description"]), ("mode", "subagent"), ("permissions", perms)]) + role_body(r)
    elif cli == "agy":
        for name in agents:
            files[base / f"agents/{name}/agent.md"] = frontmatter(
                [("name", name), ("description", description(cli, name)), ("mainAgent", True),
                 ("subagent", False)]) + orchestrator_prompt(cli, name)
            shadows.append(base / f"agents/{name}.md")
        for r in roles():
            tools = sorted({t for claude_tool in r["tools"] for t in AGY_TOOLS.get(claude_tool, [])})
            files[base / f"agents/{r['name']}/agent.md"] = frontmatter(
                [("name", r["name"]), ("description", r["description"]), ("mainAgent", False),
                 ("subagent", True), ("model", "flash" if r.get("model") == "haiku" else "inherit"),
                 ("tools", tools)]) + role_body(r)
            shadows.append(base / f"agents/{r['name']}.md")
    elif cli == "codex":
        for name in agents:  # profiles live in CODEX_HOME whatever the scope
            files[codex_home() / f"{name}.config.toml"] = toml_file(
                [("developer_instructions", orchestrator_prompt(cli, name))])
        for r in roles():
            files[base / f"agents/{r['name']}.toml"] = toml_file(
                [("name", r["name"]), ("description", r["description"]),
                 ("sandbox_mode", "read-only" if read_only(r) else "workspace-write"),
                 ("developer_instructions", role_body(r))])
    elif cli == "cursor":
        for name in agents:
            skill_dir = base / f"skills/{name}"
            files[skill_dir / "prompt.md"] = f"<!-- {MARK} from {ROOT}. -->\n" + orchestrator_prompt(cli, name)
            files[skill_dir / "SKILL.md"] = frontmatter(
                [("name", name),
                 ("description", f"{ORCHESTRATORS[name]['summary']} Run /{name} to make this session the "
                                 f"{name} orchestrator (Option+Enter keeps it as a sticky custom mode)."),
                 ("disable-model-invocation", True)]) + (
                f"\n# {name}\n\nRead `{skill_dir / 'prompt.md'}` completely now and follow it as your "
                f"operating instructions for the rest of this session: from here on you are {name}, "
                f"running inside {ORCHESTRATORS[name]['pane']}. Read it again after any context "
                f"compaction. Then handle the user's request, if one came with this command.\n")
        for r in roles():
            files[base / f"agents/{r['name']}.md"] = frontmatter(
                [("name", r["name"]), ("description", r["description"]), ("model", "inherit"),
                 ("readonly", True if read_only(r) else None)]) + role_body(r)
    return base, files, shadows


# ------------------------------------------------------------- claude hooks
def hook_entries(scope, project):
    if scope == "project" and project.resolve() == ROOT:
        pre, post = '"$CLAUDE_PROJECT_DIR"/shared/bin/guard.py', '"$CLAUDE_PROJECT_DIR"/shared/bin/orc.py phase --hook'
    else:
        pre, post = shlex.quote(str(GUARD)), f"{shlex.quote(str(ORC))} phase --hook"
    return {"PreToolUse": {"matcher": "Bash", "hooks": [{"type": "command", "command": pre}]},
            "PostToolUse": {"matcher": "*", "hooks": [{"type": "command", "command": post}]}}


def is_our_hook(event, entry):
    suffix = HOOK_SUFFIXES[event]
    return any((h.get("command") or "").replace('"', "").replace("'", "").strip().endswith(suffix)
               for h in entry.get("hooks", []))


def merge_hooks(settings_path, entries, dry):
    """Add (entries) or remove (entries=None) our hooks; every other setting is kept."""
    if settings_path.exists():
        try:
            settings = json.loads(settings_path.read_text())
        except json.JSONDecodeError as e:
            raise SystemExit(f"{settings_path} is not valid JSON ({e}); fix it first, nothing was changed")
    else:
        settings = {}
    hooks = settings.get("hooks", {})
    for event in HOOK_SUFFIXES:
        kept = [e for e in hooks.get(event, []) if not is_our_hook(event, e)]
        if entries:
            kept.append(entries[event])
        if kept:
            hooks[event] = kept
        else:
            hooks.pop(event, None)
    if hooks:
        settings["hooks"] = hooks
    else:
        settings.pop("hooks", None)
    if dry:
        return
    backup = settings_path.with_name(settings_path.name + ".orc-backup")
    if settings_path.exists() and not backup.exists():
        shutil.copy2(settings_path, backup)
    settings_path.parent.mkdir(parents=True, exist_ok=True)
    settings_path.write_text(json.dumps(settings, indent=2, ensure_ascii=False) + "\n")


# ------------------------------------------------- claude-only mods (plugins)
def mods():
    """(marketplace, [plugins]) from .claude-plugin/marketplace.json, or None."""
    try:
        market = json.loads(read(".claude-plugin/marketplace.json"))
    except (OSError, json.JSONDecodeError):
        return None
    return market["name"], [p["name"] for p in market.get("plugins", [])]


def claude_plugin(args, cwd, dry):
    cmd = ["claude", "plugin", *args]
    if dry:
        print("  would run: " + " ".join(shlex.quote(c) for c in cmd))
        return True
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    if r.returncode != 0 and "already" not in out.lower():
        print(f"  warning: {' '.join(cmd[:4])} failed: {out.splitlines()[-1] if out else r.returncode}")
        return False
    return True


def install_mods(scope, project, dry):
    """Claude Code-only extras; the orchestrators work without them, so failures only warn."""
    found = mods()
    if not found or not shutil.which("claude"):
        return []
    market, plugins = found
    where = ["--scope", "project" if scope == "project" else "user"]
    cwd = project if scope == "project" else ROOT
    claude_plugin(["marketplace", "add", str(ROOT), *where], cwd, dry)
    done = [p for p in plugins if claude_plugin(["install", f"{p}@{market}", *where], cwd, dry)]
    if done and not dry:
        print(f"[claude] mods installed as plugins: {', '.join(done)} (marketplace {market})")
    return [f"{p}@{market}" for p in done]


def uninstall_mods(entry, scope, project, dry, others_use_market):
    where = ["--scope", "project" if scope == "project" else "user"]
    cwd = project if scope == "project" else ROOT
    for ref in entry.get("mods", []):
        claude_plugin(["uninstall", ref, *where], cwd, dry)
    found = mods()
    if entry.get("mods") and found and not others_use_market:
        claude_plugin(["marketplace", "remove", found[0], *where], cwd, dry)


# --------------------------------------------------------------- manifest
def manifest_path():
    return state_dir() / "installs.json"


def load_manifest():
    try:
        return json.loads(manifest_path().read_text())
    except (OSError, json.JSONDecodeError):
        return {}


def save_manifest(data):
    manifest_path().parent.mkdir(parents=True, exist_ok=True)
    manifest_path().write_text(json.dumps(data, indent=1) + "\n")


def used_elsewhere(manifest, key):
    return {f for k, entry in manifest.items() if k != key for f in entry.get("files", [])}


def remove_files(paths, keep, dry):
    removed = []
    for p in map(Path, paths):
        if str(p) in keep or not p.exists() or not ours(p):
            continue
        removed.append(p)
        if not dry:
            p.unlink()
            parent = p.parent  # per-agent dirs: agy agents/<name>/, cursor skills/<name>/
            if parent.parent.name in ("agents", "skills") and not any(parent.iterdir()):
                parent.rmdir()
    return removed


# ------------------------------------------------------------------ actions
def install(cli, scope, project, agents, dry, force, manifest, with_mods=True):
    base, files, shadows = plan(cli, scope, project, agents)
    key = f"{cli}|{scope}|{base}"
    conflicts = [p for p in files if p.exists() and not ours(p)]
    conflicts += [p for p in shadows if p.exists() and not ours(p)]
    if conflicts and not force:
        print(f"[{cli}] not installed: these exist and were not written by install.py "
              f"(move them away or pass --force):")
        for p in conflicts:
            print(f"  {p}")
        return False
    old = set(manifest.get(key, {}).get("files", []))
    stale = remove_files(sorted(old - {str(p) for p in files}), used_elsewhere(manifest, key), dry)
    changed = [p for p in files if not p.exists() or p.read_text() != files[p]]
    if not dry:
        for p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(files[p])
    settings = None
    if "hooks" in CLIS[cli]["caps"]:
        settings = base / "settings.json"
        merge_hooks(settings, hook_entries(scope, project), dry)
    installed_mods = install_mods(scope, project, dry) if cli == "claude" and with_mods else []
    verb = "would write" if dry else "wrote"
    print(f"[{cli}] {verb} {len(changed)} of {len(files)} files under {base}"
          + (f" (+ codex profiles in {codex_home()})" if cli == "codex" else "")
          + (f"; hooks in {settings}" if settings else "")
          + (f"; removed {len(stale)} stale" if stale else ""))
    for p in changed if dry else []:
        print(f"  {p}")
    if not dry:
        manifest[key] = {"clone": str(ROOT), "agents": agents, "files": sorted(map(str, files)),
                         "settings": str(settings) if settings else None, "mods": installed_mods,
                         "installed": datetime.datetime.now().isoformat(timespec="seconds")}
    return True


def uninstall(cli, scope, project, dry, manifest):
    base = base_dir(cli, scope, project)
    key = f"{cli}|{scope}|{base}"
    entry = manifest.get(key)
    if not entry:
        print(f"[{cli}] nothing recorded for {scope} scope at {base}")
        return
    removed = remove_files(entry.get("files", []), used_elsewhere(manifest, key), dry)
    if entry.get("settings"):
        merge_hooks(Path(entry["settings"]), None, dry)
    uninstall_mods(entry, scope, project, dry,
                   any(e.get("mods") for k, e in manifest.items() if k != key))
    print(f"[{cli}] {'would remove' if dry else 'removed'} {len(removed)} files"
          + ("; hooks removed from " + entry["settings"] if entry.get("settings") else ""))
    if not dry:
        manifest.pop(key)


def status(manifest):
    if not manifest:
        print("no installs recorded on this machine")
    for key, e in sorted(manifest.items()):
        cli, scope, base = key.split("|", 2)
        print(f"{cli:9} {scope:8} {base}  agents={','.join(e['agents'])}  files={len(e['files'])}  "
              f"from {e['clone']}  ({e['installed']})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cli", help="comma-separated: " + ", ".join(CLIS) + " (default: those on PATH)")
    ap.add_argument("--scope", choices=["global", "project"], default="global")
    ap.add_argument("--project", type=Path, default=Path.cwd(), help="project dir for --scope project")
    ap.add_argument("--agents", default="hcorc,herdorc", help="orchestrators to install")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--no-mods", action="store_true", help="skip the Claude Code-only plugins in mods/")
    ap.add_argument("--uninstall", action="store_true")
    ap.add_argument("--status", action="store_true")
    a = ap.parse_args()

    manifest = load_manifest()
    if a.status:
        return status(manifest)
    if a.cli:
        clis = [c.strip() for c in a.cli.split(",") if c.strip()]
        unknown = [c for c in clis if c not in CLIS]
        if unknown:
            ap.error(f"unknown CLI {unknown}; choose from {', '.join(CLIS)}")
    else:
        clis = [c for c, meta in CLIS.items() if shutil.which(meta["bin"])]
        if not clis:
            ap.error("none of the supported CLIs is on PATH; name them with --cli")
    agents = [x.strip() for x in a.agents.split(",") if x.strip()]
    if not agents or any(x not in ORCHESTRATORS for x in agents):
        ap.error(f"--agents takes {', '.join(ORCHESTRATORS)}")
    project = a.project.expanduser().resolve()
    if a.scope == "project" and not project.is_dir():
        ap.error(f"{project} is not a directory")

    ok = True
    for cli in clis:
        if a.uninstall:
            uninstall(cli, a.scope, project, a.dry_run, manifest)
        else:
            ok = install(cli, a.scope, project, agents, a.dry_run, a.force, manifest, not a.no_mods) and ok
    if not a.dry_run:
        save_manifest(manifest)
    if not a.uninstall and not a.dry_run and ok:
        print("\nStart an orchestrator from a Herdr pane (hcorc) or a herdr pane (herdorc):")
        for cli in clis:
            print(f"  {CLIS[cli]['label']:16} " + "  |  ".join(
                CLIS[cli]["launch"].format(name=n).replace("`", "") for n in agents))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())

        for name in agents:
            files[base / f"agents/{name}.md"] = frontmatter(
                [("name", name), ("description", description(cli, name))]) + orchestrator_prompt(cli, name)
        for r in roles():  # read-only roles say so in their prompt; Grok gets no edit-tool list here
            files[base / f"agents/{r['name']}.md"] = frontmatter(
                [("name", r["name"]), ("description", r["description"])]) + role_body(r)
        files[base / GROK_HOOKS] = grok_hooks()

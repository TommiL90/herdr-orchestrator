def orchestrator_prompt(cli, name):
    caps, values = CLIS[cli]["caps"], values_for(cli, name)

    def part(rel):
        return fill(strip_comments(conditionals(read(rel), caps)), values)

    body = glossary(cli) + part("shared/core/odd-core.md") + "\n" + part("layers/common.md") + "\n" \
        + part(f"layers/{name}.md")
    vendor = ORCHESTRATORS[name].get("vendor_skill")
    if vendor:
        up = json.loads(read(f"{vendor}/UPSTREAM.json"))
        skill = re.sub(r"\A---\n.*?\n---\n", "", read(f"{vendor}/SKILL.md"), flags=re.S)
        body += (f"\n---\n\nThe `herdr` skill follows, verbatim except for its frontmatter "
                 f"({up['ref']}, {up['source']}).\n\n" + skill.lstrip())
    return body



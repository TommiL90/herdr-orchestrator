def read(rel):
    return (ROOT / rel).read_text()


def strip_comments(text):
    return re.sub(r"<!--.*?-->\s*", "", text, flags=re.S).strip() + "\n"


def conditionals(text, caps):
    """Keep `<!-- if:flag -->...<!-- endif -->` blocks whose flag is in caps (`if:!flag`: not in caps)."""
    def keep(m):
        return m.group(3) if (m.group(2) in caps) != (m.group(1) == "!") else ""
    return re.sub(r"<!-- if:(!?)(\w+) -->\n(.*?)<!-- endif -->\n?", keep, text, flags=re.S)


def fill(text, values):
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    left = sorted(set(re.findall(r"\{\{[A-Z_]+\}\}", text)))
    if left:
        raise SystemExit(f"unfilled placeholders: {left}")
    return text


def split_frontmatter(text):
    m = re.match(r"\A---\n(.*?)\n---\n", text, flags=re.S)
    return (m.group(1), text[m.end():]) if m else ("", text)


def yaml_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    s = str(value)
    plain = (s and not re.match(r"[-?:,\[\]{}#&*!|>'\"%@`\s]", s) and ": " not in s and " #" not in s
             and not s.endswith((":", " ")) and s.lower() not in ("true", "false", "null", "yes", "no"))
    return s if plain else json.dumps(s, ensure_ascii=False)


def frontmatter(fields):
    lines = ["---", f"# {MARK} from {ROOT}. Edit the sources there and re-run it."]
    for key, value in fields:
        if value is None:
            continue
        if isinstance(value, list):
            lines.append(f"{key}:")
            for item in value:
                if isinstance(item, dict):
                    pairs = list(item.items())
                    lines.append(f"  - {pairs[0][0]}: {yaml_scalar(pairs[0][1])}")
                    lines += [f"    {k}: {yaml_scalar(v)}" for k, v in pairs[1:]]
                else:
                    lines.append(f"  - {yaml_scalar(item)}")
        else:
            lines.append(f"{key}: {yaml_scalar(value)}")
    return "\n".join(lines + ["---", ""])


def toml_file(fields):
    lines = [f"# {MARK} from {ROOT}. Edit the sources there and re-run it."]
    lines += [f"{k} = {json.dumps(v, ensure_ascii=False)}" for k, v in fields if v is not None]
    return "\n".join(lines) + "\n"



def manifest_path():
    return state_dir() / "installs.json"


_manifest_base = {}  # the manifest as this run read it: save_manifest writes only what changed since


def read_manifest():
    try:
        data = json.loads(manifest_path().read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def load_manifest():
    global _manifest_base
    data = read_manifest()
    _manifest_base = copy.deepcopy(data)
    return data


_lock_depth = 0


@contextlib.contextmanager
def manifest_lock():
    """Holds the manifest lock; nested uses in one process share it. extras.py holds it
    from load to save, since all its mods share one manifest entry."""
    global _lock_depth
    if _lock_depth:
        _lock_depth += 1
        try:
            yield
        finally:
            _lock_depth -= 1
        return
    path = manifest_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path.with_name(path.name + ".lock"), "a") as lock:
        if fcntl:
            fcntl.flock(lock, fcntl.LOCK_EX)
        _lock_depth = 1
        try:
            yield
        finally:
            _lock_depth = 0


def save_manifest(data):
    """Write the entries this run added, changed or removed onto the manifest as it is
    now, under a lock: another install (an installer in another terminal, extras.py)
    may have saved its own entries since this one loaded."""
    global _manifest_base
    path = manifest_path()
    with manifest_lock():
        current = read_manifest()
        for key in set(_manifest_base) | set(data):
            if key not in data:
                current.pop(key, None)
            elif data[key] != _manifest_base.get(key):
                current[key] = data[key]
        tmp = path.with_name(path.name + ".orc-tmp")
        tmp.write_text(json.dumps(current, indent=1) + "\n")
        tmp.replace(path)
    _manifest_base = copy.deepcopy(current)
    data.clear()
    data.update(copy.deepcopy(current))


def used_elsewhere(manifest, key):
    return {f for k, entry in manifest.items() if k != key for f in entry.get("files", [])}


def prune_generated_dirs(d):
    """Remove the per-item folders we created once empty: agy agents/<name>/, a skill
    folder skills/<name>/ and its agents/ (Codex's openai.yaml)."""
    names = set(ORCHESTRATORS) | {r["name"] for r in roles()} | {f"{a}-{c}" for a in ORCHESTRATORS for c in COMMANDS}
    while (d.name in names or (d.name == "agents" and d.parent.name in names)) and d.is_dir() and not any(d.iterdir()):
        d.rmdir()
        d = d.parent


def remove_files(paths, keep, dry):
    """Remove our links (or old copies) and the generated files behind them."""
    removed = []
    for p in map(Path, paths):
        if str(p) in keep or not present(p) or not ours(p):
            continue
        removed.append(p)
        if not dry:
            p.unlink()
            prune_generated_dirs(p.parent)
            src = dist_path(p)
            if src.is_file():
                src.unlink()
                prune(src.parent, dist_root())
    return removed


def write_links(items, dry):
    """items: {installed path: (link target, generated text or None)}. Writes
    each generated text that changed into dist and (re)points each link.
    Returns the paths whose link or target changed."""
    changed = []
    for p, (src, text) in items.items():
        fresh = text is not None and (not src.is_file() or src.read_text() != text)
        relink = not linked(p, src)
        if not (fresh or relink):
            continue
        changed.append(p)
        if dry:
            continue
        if fresh:
            src.parent.mkdir(parents=True, exist_ok=True)
            src.write_text(text)
        if relink:
            link(p, src)
    return changed


# ------------------------------------------------------------------ actions
def install(cli, scope, project, agents, dry, force, manifest, with_mods=True):
    base, files, shadows = plan(cli, scope, project, agents)
    key = f"{cli}|{scope}|{base}"
    conflicts = [p for p in [*files, *shadows] if present(p) and not ours(p)]
    if conflicts and not force:
        print(f"[{cli}] not installed: these exist and were not written by install.py "
              f"(move them away or pass --force):")
        for p in conflicts:
            print(f"  {p}")
        return False
    settings = hooks_path(cli, base)
    merged = None
    if settings:
        try:  # before anything is written: a hooks file we cannot merge stops this CLI untouched
            merged = merged_hooks(cli, settings, scope, project, True)
        except (SettingsError, AttributeError, TypeError) as e:
            print(f"[{cli}] not installed: {settings}: {e}; nothing was changed")
            return False
    for shadow in shadows:  # --force: a flat agents/<name>.md would win over our folder
        if present(shadow) and not ours(shadow) and not dry:
            aside = shadow.with_name(shadow.name + ".before-orc")
            shadow.rename(aside)
            print(f"[{cli}] moved {shadow} to {aside}: it would shadow the installed agent")
    old = set(manifest.get(key, {}).get("files", []))
    stale = remove_files(sorted(old - {str(p) for p in files}), used_elsewhere(manifest, key), dry)
    changed = write_links({p: (dist_path(p), text) for p, text in files.items()}, dry)
    if settings:
        write_settings(settings, merged, dry)
    if cli == "claude" and with_mods:
        installed_mods = install_mods(scope, project, dry, manifest.get(key, {}).get("mods", []))
    else:  # --no-mods leaves installed mods alone, and keeps them recorded for --uninstall
        installed_mods = manifest.get(key, {}).get("mods", [])
    verb = "would update" if dry else "updated"
    print(f"[{cli}] {verb} {len(changed)} of {len(files)} links under {base}"
          + (f" (+ codex profiles in {codex_home()})" if cli == "codex" else "")
          + (f"; hooks in {settings}" if settings else "")
          + (f"; removed {len(stale)} stale" if stale else ""))
    for p in changed if dry else []:
        print(f"  {p}")
    if cli == "codex" and settings and not dry:
        print(f"[codex] Codex runs a new or changed hook only once you trust it: open /hooks in codex "
              f"and approve the orchestrator guard ({settings}).")
    if not dry:
        manifest[key] = {"clone": str(ROOT), "agents": agents, "files": sorted(map(str, files)),
                         "settings": str(settings) if settings else None, "mods": installed_mods,
                         "installed": datetime.datetime.now().isoformat(timespec="seconds")}
    return True


def uninstall(cli, scope, project, dry, manifest):
    base = base_dir(cli, scope, project)
    key = f"{cli}|{scope}|{base}"
    entry = manifest.get(key)
    if not entry:
        print(f"[{cli}] nothing recorded for {scope} scope at {base}")
        return
    removed = remove_files(entry.get("files", []), used_elsewhere(manifest, key), dry)
    hooks_left = None
    if entry.get("settings"):
        try:
            path = Path(entry["settings"])
            write_settings(path, merged_hooks(cli, path, scope, project, False), dry)
        except SettingsError as e:
            hooks_left = e
    same_scope = [e for k, e in manifest.items() if k != key and k.split("|")[1:2] == [scope]]
    uninstall_mods(entry, scope, project, dry, any(e.get("mods") for e in same_scope))
    print(f"[{cli}] {'would remove' if dry else 'removed'} {len(removed)} links"
          + ("; hooks removed from " + entry["settings"] if entry.get("settings") and not hooks_left else ""))
    if hooks_left:  # keep the record, so a later --uninstall still finds the hooks to remove
        print(f"[{cli}] hooks left in place: {hooks_left}; fix it and run --uninstall again")
    if not dry:
        if hooks_left:
            manifest[key] = dict(entry, files=[], mods=[])
        else:
            manifest.pop(key)
    return not hooks_left


# ------------------------------------------------------------------ herdr-app
# The Herdr desktop Skills panel: a herdr-app mod plus two layout nodes, a
# button beside the tab bar and a collapsible column beside Files/Changes.
# Herdr's own layouts are read-only, so a shipped one is cloned first.
# The button and the tab bar share a row, held in a column named `tabs-row`:
# a tab bar that grows taller (better-tabs) resizes `tabs-row` when there is
# one, else `tabs`, and inside a row a size in px is a width.
HERDR_MOD = "orc-skills"
HERDR_LAYOUT = "main-orc"
HERDR_MARKER = ".orc-generated"  # hidden: Herdr does not reload on it
# orc-panes, names for panes: it becomes the layout's pane header, drawing through a
# copy of the header it replaced (under base/), and keeps that one in props.replaces.
HERDR_PANES = "orc-panes"
PANES_KEYS = {"ctrl-space shift-p": "orc-panes.rename"}  # beside ctrl-space shift-t (tab.rename)
PANES_HEADER = {"height": 30, "position": "top", "reveal": "always"}  # as Herdr's main layout has it


def herdr_home():
    return env_path("HERDR_APP_HOME", home() / ".config/herdr-app")


def herdr_app(*args):
    """Run herdr-app; None when it is missing or the window is not running."""
    if not shutil.which("herdr-app"):
        return None
    try:
        r = subprocess.run(["herdr-app", *args], capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return r


def herdr_json(path, default):
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return default


def herdr_find(node, node_id, parent=None):
    if node.get("id") == node_id:
        return node, parent
    for child in node.get("children", []):
        found = herdr_find(child, node_id, node)
        if found:
            return found
    return None


def herdr_toggle():
    return {"id": "orc-skills-toggle", "type": "block", "size": {"px": 104}, "window_drag": True,
            "content": {"mod": HERDR_MOD, "props": {"role": "toggle"}}}


def herdr_patch(tree):
    """Add the button and the panel column once. False if the layout has no
    `tabs` block or `work-body` row to put them beside."""
    tabs, body = herdr_find(tree, "tabs"), herdr_find(tree, "work-body")
    if not tabs or not body or tabs[1] is None:
        return False
    node, parent = tabs
    if parent.get("id") == "orc-skills-bar":  # a bar from an earlier install: put our button back if it went
        if not any(c.get("id") == "orc-skills-toggle" for c in parent.get("children", [])):
            parent["children"].append(herdr_toggle())
    else:
        parent["children"][parent["children"].index(node)] = {
            "id": "orc-skills-bar", "type": "row", "size": node.get("size", {"px": 42}), "resizable": False,
            "children": [dict(node, size={"weight": 1}),
                         herdr_toggle()]}
    bar, holder = herdr_find(tree, "orc-skills-bar")
    if holder.get("id") != "tabs-row" and not herdr_find(tree, "tabs-row"):
        holder["children"][holder["children"].index(bar)] = {
            "id": "tabs-row", "type": "column", "size": bar.get("size", {"px": 42}), "resizable": False,
            "children": [dict(bar, size={"weight": 1})]}
    if not herdr_find(tree, "orc-skills-panel"):
        body[0]["children"].append({
            "id": "orc-skills-panel", "type": "column", "hidden": True, "size": {"px": 360}, "min": 300, "max": 720,
            "children": [{"id": "orc-skills", "type": "block", "content": {"mod": HERDR_MOD}}]})
    return True


def herdr_unpatch(tree):
    wrap = herdr_find(tree, "tabs-row")
    if wrap and wrap[1] is not None:  # only the column we put around the bar
        node, parent = wrap
        kids = node.get("children", [])
        if len(kids) == 1 and kids[0].get("id") == "orc-skills-bar":
            parent["children"][parent["children"].index(node)] = dict(kids[0], size=node.get("size", {"px": 42}))
    bar = herdr_find(tree, "orc-skills-bar")
    if bar:
        node, parent = bar
        rest = [c for c in node.get("children", []) if c.get("id") != "orc-skills-toggle"]
        tabs = next((c for c in rest if c.get("id") == "tabs"), None)
        if tabs and len(rest) == 1:  # only what we wrapped: put the tab bar back
            parent["children"][parent["children"].index(node)] = dict(tabs, size=node.get("size", {"px": 42}))
        else:  # something else joined the bar since: only take our button out
            node["children"] = rest
    panel = herdr_find(tree, "orc-skills-panel")
    if panel:
        panel[1]["children"].remove(panel[0])


def herdr_write(path, text):
    tmp = path.with_name(path.name + ".orc-tmp")
    tmp.write_text(text)
    tmp.replace(path)


def stable_python():
    """python3 as PATH finds it (a version manager's shim stays valid across Python
    upgrades), else this interpreter."""
    found = shutil.which("python3")
    return os.path.abspath(found) if found else sys.executable


def herdr_tab_looks(tree):
    """The content of every block that shows a tab; its `pane` look holds the pane header."""
    found = []

    def walk(node):
        content = node.get("content") or {}
        if content.get("tab"):
            found.append(content)
        for child in (node.get("children") or []) + (node.get("floating") or []):
            walk(child)
    walk(tree)
    return found


def panes_base(tree, hp):
    """The header orc-panes draws through: the one the layout's tab blocks show (or the
    one orc-panes took the place of), else Herdr's own `pane`; None when neither is there."""
    for look in herdr_tab_looks(tree):
        content = ((look.get("pane") or {}).get("header") or {}).get("content") or {}
        mod = content.get("mod")
        if mod == HERDR_PANES:
            mod = ((content.get("props") or {}).get("replaces") or {}).get("mod")
        if mod and (hp / "mods" / mod / "main.js").is_file():
            return mod
        break
    return "pane" if (hp / "mods/pane/main.js").is_file() else None


def panes_files(hp, base):
    """orc-panes as built in dist: its sources, and under base/ the modules of the header
    it draws through (a mod can't import another mod's files). None when that header
    has no default-exported class with a me() to give the name through."""
    src = hp / "mods" / base
    head = (src / "main.js").read_text() if (src / "main.js").is_file() else ""
    if "export default class" not in head or not re.search(r"\bme\(\)\s*\{", head):
        return None
    own = ROOT / "herdr-app/mods" / HERDR_PANES
    files = {f"base/{f.name}": f.read_text() for f in sorted(src.glob("*.js"))}
    files.update({"names.js": (own / "names.js").read_text(), "mod.json": (own / "mod.json").read_text(),
                  HERDR_MARKER: f"Written by herdr-orchestrators install.py --herdr-app; base: {base}.\n"})
    files["main.js"] = (own / "main.js").read_text()  # last: changing it reloads the mod
    return files


def panes_take(tree):
    """Every tab block's pane header becomes orc-panes, which keeps the header it
    replaced (None: there was none) for panes_release. False: no block shows a tab."""
    looks = herdr_tab_looks(tree)
    for look in looks:
        added = "pane" not in look
        pane = look.setdefault("pane", {})
        header = pane.get("header")
        if header is None:
            props = {"replaces": None, **({"added": "pane"} if added else {})}
            pane["header"] = dict(PANES_HEADER, content={"mod": HERDR_PANES, "props": props})
        elif (header.get("content") or {}).get("mod") != HERDR_PANES:
            header["content"] = {"mod": HERDR_PANES, "props": {"replaces": header.get("content")}}
    return bool(looks)


def panes_release(tree):
    """Put back what panes_take replaced. True when the layout changed."""
    changed = False
    for look in herdr_tab_looks(tree):
        pane = look.get("pane") or {}
        header = pane.get("header") or {}
        content = header.get("content") or {}
        if content.get("mod") != HERDR_PANES:
            continue
        props = content.get("props") or {}
        if props.get("replaces"):
            header["content"] = props["replaces"]
        else:
            pane.pop("header", None)
            if props.get("added") == "pane" and not pane:
                look.pop("pane", None)
        changed = True
    return changed


def herdr_refusal(hp, name, force):
    """Why <herdr home>/mods/<name> can't be ours, or None."""
    dst = hp / "mods" / name
    mine = ours(dst) if dst.is_symlink() else (dst / HERDR_MARKER).exists()
    if present(dst) and not mine and not force:
        return f"{dst} exists and was not written by install.py (pass --force)"
    return None


def herdr_place(hp, name, files):
    """Write a mod's build under dist/ and link <herdr home>/mods/<name> to it. The whole
    folder is linked, not each file: Herdr refuses a module whose real path is outside
    the mod's folder. Returns (files changed, whether the link was made)."""
    dst = hp / "mods" / name
    built = dist_path(dst)
    changed = [n for n in files if not (built / n).is_file() or (built / n).read_text() != files[n]]
    built.mkdir(parents=True, exist_ok=True)
    for n in changed:
        (built / n).parent.mkdir(parents=True, exist_ok=True)
        (built / n).write_text(files[n])
    for old in (built / "base").glob("*.js") if (built / "base").is_dir() else []:
        if f"base/{old.name}" not in files:  # from the header drawn through before
            old.unlink()
    relink = not linked(dst, built)
    if relink:
        if dst.is_dir() and not dst.is_symlink():
            if (dst / HERDR_MARKER).exists():  # a copy from before installs were links
                shutil.rmtree(dst)
            else:  # --force: keep theirs outside mods/, where Herdr would load it
                aside = hp / f"{name}.before-orc"
                shutil.rmtree(aside, ignore_errors=True)
                dst.rename(aside)
                print(f"[herdr-app] moved the existing {dst} to {aside}")
        link(dst, built)
    elif changed:
        # Herdr reloads a mod when its folder in mods/ changes, and its watcher
        # doesn't look through the link: making the link again loads the new build.
        link(dst, built)
    return changed, relink


def herdr_unplace(hp, name):
    dst = hp / "mods" / name
    if dst.is_symlink():
        if ours(dst):
            dst.unlink()
    elif (dst / HERDR_MARKER).exists():
        shutil.rmtree(dst)  # a copy from before installs were links
    built = dist_path(dst)
    if (built / HERDR_MARKER).exists():
        shutil.rmtree(built)
        prune(built.parent, dist_root())


def herdr_add_keys(label, keys, hp, record, backup=".before-orc"):
    """Bind keys in keys.json's global section where they are free; record the ones
    added (a key the user bound to the same action stays theirs)."""
    path = hp / "keys.json"
    data = herdr_json(path, None)
    if data is None:
        print(f"[{label}] keys not added: {path} is missing or not JSON (open Herdr once): " + ", ".join(keys))
        return
    g = data.setdefault("global", {})
    added, taken = [], []
    for key, value in keys.items():
        if key not in g:
            g[key] = value
            added.append(key)
        elif g[key] != value:
            taken.append(key)
            continue
        elif key not in record.get("keys", {}):
            continue
        record.setdefault("keys", {})[key] = value
    if added:
        saved = path.with_name(path.name + backup)
        if not saved.exists():
            shutil.copy2(path, saved)
        herdr_write(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    if added or taken:
        print(f"[{label}] keys: " + ", ".join(added or ["none added"])
              + (f"; already bound to something else, left alone: {', '.join(taken)}" if taken else ""))


def herdr_drop_keys(hp, record, names, label="keys"):
    """Unbind the recorded keys among `names` that still do what we bound."""
    path = hp / "keys.json"
    data = herdr_json(path, None)
    ours_ = record.get("keys", {})
    drop = set(names) & set(ours_)
    if data is None or not drop:
        return
    g = data.get("global", {})
    removed = [k for k in drop if g.get(k) == ours_[k]]
    for k in removed:
        g.pop(k)
    for k in drop:
        ours_.pop(k)
    if removed:
        herdr_write(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        print(f"[{label}] removed {', '.join(sorted(removed))}")


def panes_hand_back(hp, manifest):
    """Before another installer edits the layout orc-panes is in: give the header back,
    so that installer finds the one it knows (herdr-nvim adds its button to Herdr's)."""
    entry = manifest.get(f"herdr-app|{hp}") or {}
    path = hp / "layouts" / f"{entry.get('layout')}.json"
    tree = herdr_json(path, None) if "panes" in entry else None
    if tree is not None and panes_release(tree):
        herdr_write(path, json.dumps(tree, indent=2) + "\n")


def panes_take_back(hp, manifest):
    """After it: draw through whatever header the layout shows now."""
    entry = manifest.get(f"herdr-app|{hp}") or {}
    path = hp / "layouts" / f"{entry.get('layout')}.json"
    tree = herdr_json(path, None) if "panes" in entry else None
    if tree is None:
        return
    base = panes_base(tree, hp)
    files = base and panes_files(hp, base)
    if not files:
        print(f"[herdr-app] pane names left out: layout {entry['layout']} has a pane header orc-panes can't draw through")
        return
    herdr_place(hp, HERDR_PANES, files)
    if panes_take(tree):
        herdr_write(path, json.dumps(tree, indent=2) + "\n")
    entry["panes"] = {"base": base}


def herdr_mod_files():
    """The mod as built in dist: the sources, with config.js pointing at this
    clone. main.js goes last because changing it reloads the mod. The whole
    folder is linked, not each file: Herdr refuses a module whose real path is
    outside the mod's folder."""
    src = ROOT / "herdr-app/mods" / HERDR_MOD
    files = {"config.js": "// Generated by herdr-orchestrators install.py; re-run it after moving the clone.\n"
                          f"export const ORC = {json.dumps(str(ROOT / 'shared/bin/orc.py'))};\n"
                          f"export const PYTHON = {json.dumps(stable_python())};\n",
             HERDR_MARKER: "Written by herdr-orchestrators install.py --herdr-app.\n"}
    for name in ("skills.js", "icon.svg", "mod.json", "main.js"):
        files[name] = (src / name).read_text()
    return files


def install_herdr_app(dry, force, manifest):
    hp = herdr_home()
    key = f"herdr-app|{hp}"
    if not (hp / "layouts").is_dir():
        print(f"[herdr-app] skipped: no Herdr app home at {hp} (open Herdr once, or set HERDR_APP_HOME)")
        return True
    dst, pdst = hp / "mods" / HERDR_MOD, hp / "mods" / HERDR_PANES
    built = dist_path(dst)
    for name in (HERDR_MOD, HERDR_PANES):
        refusal = herdr_refusal(hp, name, force)
        if refusal:
            print(f"[herdr-app] not installed: {refusal}")
            return False
    entry = manifest.get(key, {})
    shown = herdr_json(hp / "shared.json", {}).get("layout") or "main"
    shipped = {k.split(":", 1)[1] for k in herdr_json(hp / "installed.json", {}) if k.startswith("layout:")}
    target = entry.get("layout")
    if not target or not (hp / "layouts" / f"{target}.json").exists():
        own = shown not in shipped and (hp / "layouts" / f"{shown}.json").exists()
        target = shown if own else HERDR_LAYOUT
    layout_path = hp / "layouts" / f"{target}.json"
    create = not layout_path.exists()
    if create and not (hp / "layouts/main.json").exists():
        print(f"[herdr-app] not installed: no layout to start from ({hp / 'layouts/main.json'} is missing; open Herdr once)")
        return False
    if not create and not herdr_patch(herdr_json(layout_path, {})):
        print(f"[herdr-app] not installed: layout {target} has no `tabs` block or `work-body` row "
              f"to put the Skills panel beside")
        return False
    files = herdr_mod_files()
    if dry:
        changed = [n for n in files if not (built / n).is_file() or (built / n).read_text() != files[n]]
        base = panes_base(herdr_json(hp / "layouts" / ("main.json" if create else f"{target}.json"), {}), hp)
        print(f"[herdr-app] would write {len(changed)} of {len(files)} files under {built}"
              + (f" and link {dst} to it" if not linked(dst, built) else "") + "; "
              + (f"would clone layout main as {target} and switch to it" if create else f"would add the panel to layout {target}")
              + (f"; would make orc-panes the pane header, drawing through {base}" if base and panes_files(hp, base)
                 else "; pane names left out (no pane header orc-panes can draw through)"))
        return True
    changed, relink = herdr_place(hp, HERDR_MOD, files)
    # Recorded now, so --uninstall finds it even if a step below fails. created_layout
    # stays true only for the layout this installer cloned, not one it found later.
    manifest[key] = {"clone": str(ROOT), "agents": [], "files": [str(dst)], "layout": target,
                     "created_layout": create or (entry.get("created_layout", False) and entry.get("layout") == target),
                     "previous_layout": entry.get("previous_layout") or shown,
                     "keys": entry.get("keys", {}),
                     "installed": datetime.datetime.now().isoformat(timespec="seconds")}
    note = ""
    if create:
        r = herdr_app("do", "layout.clone", json.dumps({"name": "main", "as": target}))
        if not (r and r.returncode == 0 and layout_path.exists()):
            # Herdr is not running: copy the shipped file; it is picked with ctrl-shift-l.
            herdr_write(layout_path, (hp / "layouts/main.json").read_text())
            note = f"; Herdr is not running: pick layout {target} with ctrl-shift-l"
    tree = herdr_json(layout_path, None)
    before = json.dumps(tree)
    if tree is None or not herdr_patch(tree):
        print(f"[herdr-app] mod written, but layout {target} could not be patched")
        return False
    # Pane names: the mod first, then the header that shows it.
    base = panes_base(tree, hp)
    pane_files = base and panes_files(hp, base)
    if pane_files:
        herdr_place(hp, HERDR_PANES, pane_files)
        manifest[key]["files"].append(str(pdst))
        manifest[key]["panes"] = {"base": base}
        panes_take(tree)
    if json.dumps(tree) != before:  # a rerun leaves the layout file alone
        herdr_write(layout_path, json.dumps(tree, indent=2) + "\n")
    check = herdr_app("check", str(dst))
    if check is not None and check.returncode != 0:
        print(f"[herdr-app] herdr-app check failed:\n{(check.stdout + check.stderr).strip()}")
        return False
    names = "pane names left out (no pane header orc-panes can draw through)"
    if pane_files:
        pcheck = herdr_app("check", str(pdst))
        if pcheck is not None and pcheck.returncode != 0:  # give the layout its own header back
            if panes_release(tree):
                herdr_write(layout_path, json.dumps(tree, indent=2) + "\n")
            print(f"[herdr-app] herdr-app check of orc-panes failed:\n{(pcheck.stdout + pcheck.stderr).strip()}")
            return False
        herdr_add_keys("herdr-app", PANES_KEYS, hp, manifest[key])
        names = f"pane names in its pane header (drawing through {base})"
    print(f"[herdr-app] wrote {len(changed)} of {len(files)} files under {built}"
          + (f", linked {dst} to it" if relink else "") + f"; Skills panel in layout {target}"
          + (" (cloned from main)" if create else "") + f"; {names}" + note
          + ("; herdr-app check passed" if check is not None else ""))
    return True


def uninstall_herdr_app(dry, manifest):
    hp = herdr_home()
    key = f"herdr-app|{hp}"
    entry = manifest.get(key)
    if not entry:
        print(f"[herdr-app] nothing recorded for {hp}")
        return
    layout_path = hp / "layouts" / f"{entry['layout']}.json"
    dst = hp / "mods" / HERDR_MOD
    if dry:
        print(f"[herdr-app] would remove {dst}, {hp / 'mods' / HERDR_PANES} and "
              + (f"layout {entry['layout']}" if entry.get("created_layout") else f"the panel from layout {entry['layout']}"))
        return
    if layout_path.exists():
        if entry.get("created_layout"):
            if herdr_json(hp / "shared.json", {}).get("layout") == entry["layout"]:
                herdr_app("do", "layout.switch", json.dumps({"name": entry.get("previous_layout") or "main"}))
            layout_path.unlink()
        else:
            tree = herdr_json(layout_path, None)
            if tree is not None:
                herdr_unpatch(tree)
                panes_release(tree)
                herdr_write(layout_path, json.dumps(tree, indent=2) + "\n")
    herdr_drop_keys(hp, entry, PANES_KEYS, "herdr-app")
    herdr_unplace(hp, HERDR_MOD)
    herdr_unplace(hp, HERDR_PANES)
    print(f"[herdr-app] removed {dst}, pane names and "
          + (f"layout {entry['layout']}" if entry.get("created_layout") else f"the panel from layout {entry['layout']}"))
    manifest.pop(key)


